// T010 — CLI build step (second half of `npm run build`).
//
// `vite build` (first half) builds the React UI into dist/. This
// script then compiles the Node CLI (src/cli + src/core + src/report
// + src/worker) into dist/ with tsc (tsconfig.cli.json, NodeNext
// modules) and writes the dist/checkpath.mjs launcher that the
// acceptance commands invoke:
//
//   node dist/checkpath.mjs demo | analyze ... | matrix ...
//
// The launcher only re-exports main() from the compiled CLI and
// applies its returned exit code; it contains no logic of its own.

import { spawnSync } from "node:child_process";
import { chmodSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const tsc = join(repoRoot, "node_modules", ".bin", "tsc");

const result = spawnSync(tsc, ["-p", "tsconfig.cli.json"], {
  cwd: repoRoot,
  stdio: "inherit",
});
if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const launcher = `#!/usr/bin/env node
// T010 — dist launcher (generated by scripts/build-cli.mjs).
import { main } from "./cli/index.js";

process.exitCode = await main(process.argv.slice(2));
`;
const launcherPath = join(repoRoot, "dist", "checkpath.mjs");
writeFileSync(launcherPath, launcher, "utf8");
chmodSync(launcherPath, 0o755);
console.log(`wrote ${launcherPath}`);
